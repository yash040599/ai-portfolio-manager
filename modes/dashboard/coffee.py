"""The "Buy me a coffee" button in the dashboard navigation, mirroring Rupevo's.

The dialog shows the maintainer's UPI QR code and UPI ID: the same public
details Rupevo publishes in its `site/assets/js/config.js`. There is
deliberately no pay link: UPI apps reject `upi://pay` links to a personal
UPI ID, so a payment starts in the app by scanning the code or typing the ID.

To change the details, update `UPI_ID` and `PAYEE` here and copy Rupevo's
`site/assets/img/upi-qr.svg` (regenerated by its `scripts/make_upi_qr.py`)
over `assets/upi-qr.svg`.
"""

from __future__ import annotations

from functools import lru_cache
import html
import json
from pathlib import Path

from modes.dashboard.icons import icon


UPI_ID = "yash040599@okhdfcbank"
PAYEE = "Yash Agrawal"

_QR_PATH = Path(__file__).with_name("assets") / "upi-qr.svg"


@lru_cache(maxsize=1)
def _qr_svg() -> str:
    try:
        return _QR_PATH.read_text(encoding="utf-8").strip()
    except OSError:
        return ""


def coffee_button_html() -> str:
    """App-bar button; the dialog itself is built on first click."""
    return (
        '<button class="nav-coffee" type="button" onclick="openDashboardCoffee()" '
        'aria-haspopup="dialog" aria-label="Buy me a coffee" '
        'title="Buy me a coffee: support this project via UPI">'
        f'{icon("coffee", size=20)}<span class="nav-coffee-text">Buy me a coffee</span></button>'
    )


def coffee_dialog_html() -> str:
    qr = _qr_svg()
    figure = (f'<figure class="qr-card">{qr}<figcaption>Scan with any UPI app</figcaption></figure>'
              if qr else "")
    return (
        '<dialog class="coffee-dialog" aria-labelledby="coffee-title" data-privacy-public>'
        '<form method="dialog" class="coffee-shell">'
        '<div class="coffee-head"><h2 id="coffee-title">Buy me a coffee &#9749;</h2>'
        '<button class="coffee-x" value="close" aria-label="Close">&times;</button></div>'
        '<p>This dashboard and Rupevo are free and ad-free. If they helped you, chip in '
        'any amount you like &mdash; a coffee is about &#8377;100. Thank you!</p>'
        f'<div class="coffee-grid">{figure}<div class="coffee-side">'
        '<div class="coffee-label">UPI ID</div>'
        f'<div class="upi-id"><code>{html.escape(UPI_ID)}</code>'
        '<button class="action alt" type="button" data-coffee-copy>Copy</button></div>'
        f'<div class="coffee-label">Paid to {html.escape(PAYEE)}</div>'
        '</div></div>'
        '<p class="coffee-note">Scan the code with your phone, or pay the UPI ID from any '
        "UPI app. Payments go straight to the maintainer's bank account; this dashboard "
        'never sees your payment details.</p>'
        '<div class="coffee-actions"><button class="action" value="close">Close</button></div>'
        '</form></dialog>'
    )


_SCRIPT = r"""
<script>
(function () {
  if (window.openDashboardCoffee) return;
  var MARKUP = __MARKUP__;
  var UPI_ID = __UPI__;
  var dialog = null;

  function copyId(button) {
    function done(copied) {
      if (!copied) {
        var range = document.createRange();
        range.selectNodeContents(dialog.querySelector('.upi-id code'));
        var selection = window.getSelection();
        selection.removeAllRanges();
        selection.addRange(range);
      }
      button.textContent = copied ? 'Copied \u2713'
        : (/Mac|iPhone|iPad/.test(navigator.platform || '') ? 'Press \u2318C' : 'Press Ctrl+C');
      setTimeout(function () { button.textContent = 'Copy'; }, 2500);
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(UPI_ID).then(function () { done(true); }, function () { done(false); });
    } else {
      done(false);
    }
  }

  window.openDashboardCoffee = function () {
    if (!dialog) {
      var holder = document.createElement('div');
      holder.innerHTML = MARKUP;
      dialog = holder.firstElementChild;
      document.body.appendChild(dialog);
      // The form fills the dialog, so only a backdrop click targets it.
      dialog.addEventListener('click', function (event) {
        if (event.target === dialog) dialog.close();
      });
      dialog.querySelector('[data-coffee-copy]').addEventListener('click', function (event) {
        copyId(event.currentTarget);
      });
    }
    if (typeof dialog.showModal === 'function') {
      if (!dialog.open) dialog.showModal();
    } else {
      dialog.setAttribute('open', '');
    }
  };
})();
</script>
"""


def coffee_script() -> str:
    """Head script; `theme_boot_script()` includes it on every page."""
    markup = json.dumps(coffee_dialog_html()).replace("</", "<\\/")
    return _SCRIPT.replace("__MARKUP__", markup).replace("__UPI__", json.dumps(UPI_ID))


